// Функция на всякий случай вырезает любые длинные и средние тире перед выводом на экран
export function sanitizeText(value) {
  if (typeof value !== 'string') return '';
  return value.replace(/[\u2014\u2013]/g, ', ');
}

// Подставляет переменные вроде {creator}, {friend}, {code} в строку
export function formatText(template, vars = {}) {
  let result = sanitizeText(template);
  for (const [key, val] of Object.entries(vars)) {
    result = result.split(`{${key}}`).join(sanitizeText(String(val)));
  }
  return result;
}

